"""Generate clearly labeled synthetic audio so the harness can be tried.

These files are examples. They are not room simulations, field recordings,
or results from an experiment.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from acousticbench.audio import write_wav
from acousticbench.eval.store import Store
from acousticbench.service import add_dataset

SAMPLE_RATE = 16000
DURATION = 1.0
SEED = 20261117
PER_CLASS = 8
CLASSES = ("chirp", "noise", "tone")

EXAMPLE_DATASETS = (
    {
        "id": "example-sim-clean",
        "name": "Example simulated clean signals",
        "domain": "simulated",
        "folder": "sim_clean",
        "degraded": False,
        "synthetic_stand_in": False,
        "description": (
            "EXAMPLE. Generated tones, noise, and chirps with no extra degradation. "
            "This stands in for a simulated-domain dataset. It is not the output of a "
            "room simulator and it is not study data."
        ),
    },
    {
        "id": "example-synthetic-realish",
        "name": "Example synthetic stand-in for real audio",
        "domain": "real",
        "folder": "synthetic_realish",
        "degraded": True,
        "synthetic_stand_in": True,
        "description": (
            "EXAMPLE / SYNTHETIC STAND-IN. The same kinds of generated signals with "
            "noise, random gain, and low-pass filtering. Registered in the real domain "
            "only so the comparison screen can be tried. These are not real recordings "
            "and scores on them are not experimental results."
        ),
    },
)


def generate_example_datasets(project_root: Path, store: Store) -> list[dict]:
    root = project_root / "data" / "examples"
    registered = []
    for spec in EXAMPLE_DATASETS:
        folder = root / spec["folder"]
        _write_condition(folder, degraded=spec["degraded"], domain=spec["domain"])
        record = add_dataset(
            store,
            {
                "id": spec["id"],
                "name": spec["name"],
                "domain": spec["domain"],
                "layout": "class_folders",
                "root_path": folder,
                "description": spec["description"],
                "is_example": True,
                "synthetic_stand_in": spec["synthetic_stand_in"],
                "metadata": {
                    "synthetic": True,
                    "example": True,
                    "generator": "acousticbench.examples_data",
                    "seed": SEED,
                    "sample_rate": SAMPLE_RATE,
                    "classes": list(CLASSES),
                    "not_experimental_results": True,
                },
            },
            allow_example_flags=True,
        )
        registered.append(record)
    return registered


def synthesize(kind: str, rng: np.random.Generator, sample_rate: int = SAMPLE_RATE, duration: float = DURATION) -> np.ndarray:
    count = int(sample_rate * duration)
    time = np.arange(count, dtype=np.float64) / sample_rate
    if kind == "tone":
        frequency = float(rng.choice([220.0, 440.0, 660.0, 880.0, 1320.0]))
        signal = 0.6 * np.sin(2.0 * np.pi * frequency * time)
    elif kind == "noise":
        signal = rng.normal(0.0, 0.25, size=count)
    elif kind == "chirp":
        start = float(rng.uniform(150.0, 600.0))
        end = float(rng.uniform(1800.0, 5000.0))
        if rng.random() < 0.5:
            start, end = end, start
        phase = 2.0 * np.pi * (start * time + (end - start) * time**2 / (2.0 * duration))
        signal = 0.6 * np.sin(phase)
    else:
        raise ValueError(f"Unknown example class '{kind}'.")
    return signal.astype(np.float64)


def degrade(audio: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    noisy = audio * float(rng.uniform(0.35, 0.85)) + rng.normal(0.0, 0.18, size=audio.shape)
    alpha = 0.08
    filtered = np.empty_like(noisy)
    filtered[0] = noisy[0]
    for index in range(1, len(noisy)):
        filtered[index] = (1.0 - alpha) * filtered[index - 1] + alpha * noisy[index]
    return np.clip(filtered, -1.0, 1.0)


def _write_condition(folder: Path, *, degraded: bool, domain: str) -> None:
    if folder.exists():
        for path in folder.rglob("*"):
            if path.is_file():
                path.unlink()
    rng = np.random.default_rng(SEED + (1 if degraded else 0))
    for label in CLASSES:
        for index in range(PER_CLASS):
            signal = synthesize(label, rng)
            if degraded:
                signal = degrade(signal, rng)
            write_wav(folder / label / f"{label}_{index:02d}.wav", signal, SAMPLE_RATE)
    notice = (
        "EXAMPLE SYNTHETIC AUDIO\n"
        "Generated by AcoustiBench. Not a real recording, not a room simulation,\n"
        "and not an experimental result.\n"
        f"domain label used by the harness: {domain}\n"
        f"degraded: {degraded}\n"
        f"seed: {SEED}\n"
    )
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "EXAMPLE.txt").write_text(notice, encoding="utf-8")
    (folder / "metadata.json").write_text(
        json.dumps(
            {
                "example": True,
                "synthetic": True,
                "not_experimental_results": True,
                "domain": domain,
                "degraded": degraded,
                "seed": SEED,
                "sample_rate": SAMPLE_RATE,
                "classes": list(CLASSES),
            },
            indent=2,
        ),
        encoding="utf-8",
    )
