"""Development impulse responses from Pyroomacoustics.

The reference T60 is the Sabine value for the absorption used in the shoebox.
Air absorption is off. Image order is finite, so a Schroeder estimate can
differ from the Sabine label. These files are simulated development data, not
the sponsor's SoundSpaces or Steam Audio set, and not real recordings.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from acousticbench.audio import write_wav
from acousticbench.eval.store import Store
from acousticbench.service import add_dataset
from acousticbench.sim.sabine import sabine_t60

SAMPLE_RATE = 16000
IMAGE_ORDER = 40
DATASET_ID = "pyroom-sabine-dev"

ROOMS = (
    {"condition": "office", "dimensions": (4.0, 3.5, 2.8), "target_t60": 0.35},
    {"condition": "meeting", "dimensions": (6.0, 5.0, 2.9), "target_t60": 0.60},
    {"condition": "lecture", "dimensions": (8.0, 6.5, 3.2), "target_t60": 0.95},
)
SOURCE_FRACTION = (0.28, 0.35, 0.45)
MICROPHONE_FRACTIONS = (
    (0.62, 0.58, 0.50),
    (0.70, 0.40, 0.55),
)


def generate_pyroom_dataset(project_root: Path, store: Store) -> dict:
    try:
        import pyroomacoustics as pra
    except ImportError as exc:
        raise RuntimeError(
            "Pyroomacoustics is not installed. Install it with: python -m pip install pyroomacoustics"
        ) from exc

    folder = project_root / "data" / "simulated" / "pyroom-sabine-dev"
    if folder.exists():
        for path in folder.rglob("*"):
            if path.is_file():
                path.unlink()
    audio_dir = folder / "rir"
    rows = []
    version = getattr(pra, "__version__", "unknown")
    for room in ROOMS:
        dimensions = room["dimensions"]
        absorption, _suggested_order = pra.inverse_sabine(room["target_t60"], list(dimensions))
        absorption = float(absorption)
        reference = sabine_t60(dimensions, absorption)
        source = _point(dimensions, SOURCE_FRACTION)
        for index, mic_fraction in enumerate(MICROPHONE_FRACTIONS, start=1):
            microphone = _point(dimensions, mic_fraction)
            rir = _simulate_rir(pra, dimensions, absorption, source, microphone)
            name = f"{room['condition']}_{index:02d}.wav"
            write_wav(audio_dir / name, rir, SAMPLE_RATE)
            rows.append((f"rir/{name}", reference, room["condition"]))
    manifest = folder / "manifest.csv"
    lines = ["path,t60,condition,split"]
    lines.extend(f"{path},{t60:.6f},{condition},dev" for path, t60, condition in rows)
    manifest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    notice = (
        "SIMULATED DEVELOPMENT DATA\n"
        "Generated by Pyroomacoustics shoebox image-source simulation.\n"
        "The t60 column is the Sabine reverberation time for the wall absorption.\n"
        "It is not a measured T60 and not a sponsor SoundSpaces or Steam Audio export.\n"
        f"pyroomacoustics {version}; sample rate {SAMPLE_RATE}; image order {IMAGE_ORDER}; air absorption off.\n"
    )
    (folder / "SIMULATED.txt").write_text(notice, encoding="utf-8")
    (folder / "metadata.json").write_text(
        json.dumps(
            {
                "simulator": "pyroomacoustics",
                "simulator_version": version,
                "reference": "sabine",
                "sample_rate": SAMPLE_RATE,
                "image_order": IMAGE_ORDER,
                "air_absorption": False,
                "not_a_measured_recording": True,
                "not_sponsor_dataset": True,
                "citation": "Scheibler, Bezzam, and Dokmanic, ICASSP 2018",
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    return add_dataset(
        store,
        {
            "id": DATASET_ID,
            "name": "Pyroomacoustics Sabine development set",
            "domain": "simulated",
            "layout": "csv",
            "root_path": folder,
            "description": (
                "Shoebox impulse responses from Pyroomacoustics. The t60 column is the Sabine "
                "value for the absorption used in the simulation, not a measured reverberation time. "
                "Development data only. Not the sponsor SoundSpaces or Steam Audio dataset."
            ),
            "is_example": False,
            "synthetic_stand_in": False,
            "metadata": {
                "simulator": "pyroomacoustics",
                "simulator_version": version,
                "reference": "sabine",
                "development": True,
            },
        },
        allow_example_flags=True,
    )


def _simulate_rir(pra, dimensions, absorption, source, microphone) -> np.ndarray:
    room = pra.ShoeBox(
        list(dimensions),
        fs=SAMPLE_RATE,
        materials=pra.Material(absorption),
        max_order=IMAGE_ORDER,
        air_absorption=False,
    )
    room.add_source(list(source))
    room.add_microphone(list(microphone))
    room.compute_rir()
    rir = np.asarray(room.rir[0][0], dtype=np.float64)
    peak = float(np.max(np.abs(rir))) if rir.size else 0.0
    if peak > 0:
        rir = 0.9 * rir / peak
    return rir


def _point(dimensions: tuple[float, float, float], fractions: tuple[float, float, float]) -> tuple[float, float, float]:
    return tuple(length * fraction for length, fraction in zip(dimensions, fractions))
